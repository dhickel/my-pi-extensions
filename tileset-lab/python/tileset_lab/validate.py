PRODUCER = "tileset-lab/native-producer"


def _json(root, path):
    content = root.read(path)[0]
    require(len(content) <= 128*1024*1024, "Oversized native proof; no truncated/partial parser")
    value = parse_json(content, path)
    require(type(value) is dict, f"{path}: native proof must be a JSON object")
    return value


def _counts(value, label):
    require(type(value) is dict, label + ": counts must be an object")
    for key, number in value.items():
        require(type(key) is str, label + ": count name must be text")
        integer(number, label + " " + key)
    return value


def _stats(value):
    return _counts(closed(value, ("cells", "objects"), "native visible art stats"), "native visible art stats")


def _approval(value):
    closed(value, ("path", "sha256", "reviewer", "packet", "tool_sha256", "roles", "test_only", "actual_visual_approval"), "bound source approval")
    integer(value["roles"], "source approval role count", 1)
    reviewer = closed(value["reviewer"], ("id", "kind", "independent_of", "image_capable"), "source reviewer")
    boolean(reviewer["image_capable"], "source reviewer image capability")
    for key in ("test_only", "actual_visual_approval"):
        boolean(value[key], "source approval " + key)
    return value


def _candidate(inputs, manifest, manifest_path, candidate, *, allow_test_trust=False):
    identifier(candidate, "candidate id")
    directory = f"{manifest['output_root']}/candidates/{candidate}"
    root = inputs.root
    require(root.exists(directory) and root.exists(f"{directory}/report.json"), "Missing complete stable candidate")
    report = _json(root, f"{directory}/report.json")
    closed(report, ("schema_version", "operation", "status", "consumer", "id", "candidate_path", "selected",
                    "source_approval", "tool_sha256", "input_hashes", "output_inventory", "provenance", "owned_paths",
                    "counts", "native_proof", "native_visual_approval", "limitations"), "complete candidate report")
    require(type(report["schema_version"]) is int and report.get("schema_version") == 1 and report.get("operation") == "build"
            and report.get("consumer") == manifest["id"] and report.get("id") == candidate
            and report.get("candidate_path") == directory and report.get("selected") is False
            and report.get("status") in ("CANDIDATE", "CANDIDATE_TEST_ONLY"), "Wrong/incomplete candidate identity")
    require(report["native_proof"] is False and report["native_visual_approval"] is False, "Candidate falsely claims native proof")
    _counts(report["counts"], "candidate")
    _approval(report["source_approval"])
    identity = tool_identity()
    require(report["tool_sha256"] == identity["sha256"], "Stale candidate executable/dependency content")
    for key, expected_path in (("output_inventory", f"{directory}/output-inventory.json"), ("provenance", f"{directory}/provenance.json")):
        reference = closed(report[key], ("path", "sha256"), "candidate " + key)
        relative_path(reference["path"])
        digest(reference["sha256"])
        require(reference["path"] == expected_path, "Candidate proof reference escapes exact candidate")
    inv = report["output_inventory"]
    require(sha256(root.read(inv["path"])[0]) == inv["sha256"], "Changed candidate build inventory")
    inventory = closed(_json(root, inv["path"]), ("schema_version", "consumer", "candidate", "files"), "candidate build inventory")
    require(type(inventory["schema_version"]) is int and inventory["schema_version"] == 1
            and inventory["consumer"] == manifest["id"] and inventory["candidate"] == candidate, "Wrong build inventory identity")
    rows = array(inventory["files"], "complete candidate build files", True)
    for row in rows:
        check_file(root, row)
    unique([r["path"] for r in rows], "candidate build inventory")
    allowed = {r["path"] for r in rows} | {inv["path"], f"{directory}/report.json"}
    require(all(path in allowed or PurePosixPath(f"{directory}/native") in PurePosixPath(path).parents
                for path in root.files(directory)), "Foreign candidate file; ownership uncertain")
    require(type(report["input_hashes"]) is dict, "Candidate protected inputs must be an object")
    for path, expected in report["input_hashes"].items():
        require(sha256(inputs.read(path)) == expected, f"Stale candidate protected input: {path}")
    originals = validate_inventory(inputs, manifest)
    sources = load_sources(inputs, manifest)
    catalogs = load_catalogs(inputs, manifest, sources)
    frozen_doc, frozen = load_frozen(inputs, manifest, catalogs, sources)
    approval = check_source_geometry(inputs, manifest, manifest_path, sources, catalogs, frozen_doc, frozen,
                                     allow_test_trust=allow_test_trust)
    require(report["source_approval"] == approval, "Fresh source approval does not bind THIS candidate")
    scenes = load_scenes(inputs, manifest, catalogs, sources)
    registrations, terrains, parts = expectation.original_assets(inputs, manifest, directory, sources, catalogs, frozen)
    descriptions = expectation.descriptions(manifest, directory, catalogs, scenes, registrations, terrains, parts)
    provenance = _json(root, report["provenance"]["path"])
    require(sha256(root.read(report["provenance"]["path"])[0]) == report["provenance"]["sha256"], "Stale candidate provenance")
    require({d["path"] for d in descriptions} == {m["path"] for m in provenance["maps"]}, "Incomplete independent original gallery/scene inventory")
    for description in descriptions:
        expectation.verify_map(root, description, manifest["cell_size"])
    return {"directory": directory, "native_directory": f"{directory}/native", "candidate": candidate,
            "identity": identity, "approval": approval, "source_author": frozen_doc["author_id"],
            "originals": originals, "sources": sources, "catalogs": catalogs, "frozen": frozen,
            "registrations": registrations, "terrains": terrains, "parts": parts, "descriptions": descriptions}


def _stage_paths(native, item):
    stem = f"{native}/stages/{item['id']}"
    return {"tmx": stem+".tmx", "record": stem+".record.json", "png": stem+".png",
            "overlay": stem+".overlay.png" if item["mode"] == "alpha" else None,
            "ground": stem+".ground.png" if item["mode"] == "alpha" else None,
            "expected": f"{native}/expected/{item['id']}.png",
            "expected_overlay": f"{native}/expected/{item['id']}.overlay.png" if item["mode"] == "alpha" else None,
            "intent_png": f"{native}/intent/{item['id']}.png"}


def _declaration(manifest, state):
    native, size = state["native_directory"], manifest["cell_size"]
    families = [{"pack": pack, "family": family, "mode": a["family"]["mode"]} for (pack, family), a in state["terrains"].items()]
    draw = drawcases.inventory(manifest["id"], families, size)
    items = []
    for original in draw["items"]:
        item = {**original, **_stage_paths(native, original), "context": None, "elapsed_ms": 0}
        item["crops"] = [{"id": c["id"], "pixel_rect": [v*size for v in c["cell_rect"]],
                          "actual": f"{native}/crops/{item['id']}/{c['id']}-native.png",
                          "expected": f"{native}/crops/{item['id']}/{c['id']}-expected.png"} for c in original["crops"]]
        item["pages"] = [{"id": name, "path": f"{native}/pages/{item['id']}/{name}.png"} for name in original["pages"]]
        items.append(item)
    contexts = []
    for description in state["descriptions"]:
        declaration = expectation.declaration(description)
        recipe_sha = sha256(json_bytes(declaration))
        name = f"{description['kind']}-{PurePosixPath(description['path']).stem}"
        ps = expectation.primitives(description, size)
        entities = list(dict.fromkeys(p["entity"] for p in ps))
        for elapsed in expectation.times(description, size):
            key = f"{name}-{elapsed}ms"
            rectangles = []
            for index, entity in enumerate(entities):
                group = [p for p in ps if p["entity"] == entity]
                boxes = [(p["x"], p["y"], p["asset"]["images"][p["local"]].width, p["asset"]["images"][p["local"]].height) for p in group]
                left, top = min(b[0] for b in boxes), min(b[1] for b in boxes)
                right, bottom = max(b[0]+b[2] for b in boxes), max(b[1]+b[3] for b in boxes)
                rectangles.append({"id": f"entity-{index:04d}", "entity": entity, "pixel_rect": [left, top, right-left, bottom-top],
                    "actual": f"{native}/crops/context-{key}/entity-{index:04d}-native.png",
                    "expected": f"{native}/crops/context-{key}/entity-{index:04d}-expected.png"})
            pages = []
            # Pages cover the WHOLE native canvas, not only occupied bounding boxes.
            for y in range(0, description["height"]*size, 600):
                for x in range(0, description["width"]*size, 600):
                    rect = [x, y, min(600, description["width"]*size-x), min(600, description["height"]*size-y)]
                    for context in ("ground", "checker"):
                        page_id = f"{x}-{y}-{context}"
                        pages.append({"id": page_id, "context": context, "pixel_rect": rect,
                                      "path": f"{native}/pages/context-{key}/{page_id}.png"})
            actual = f"{native}/contexts/{key}.png" if elapsed == 0 else f"{native}/animation/{key}1.png"
            context = {"key": key, "map": description["path"], "width": description["width"], "height": description["height"],
                       "elapsed_ms": elapsed, "png": actual, "export": f"{native}/exports/maps/{name}.tmj"}
            contexts.append(context)
            items.append({"id": f"context/{key}", "kind": description["kind"], "consumer": manifest["id"],
                          "pack": None, "family": None, "mode": None, "case": None, "stage": None, "cell_size": size,
                          "context": key, "elapsed_ms": elapsed, "intent": "Complete original source/component/frame/gallery/scene intent; effective visibility, exact geometry and strict elapsed>duration playback.",
                          "field_sha256": recipe_sha, "recipe_sha256": recipe_sha, "map": description["path"],
                          "png": actual, "expected": f"{native}/expected/context-{key}.png", "intent_png": None,
                          "crops": rectangles, "pages": pages})
    unique([i["id"] for i in items], "FULL independent draw/art review inventory")
    return {"schema_version": 1, "consumer": manifest["id"], "candidate": state["candidate"],
            "draw": draw, "contexts": contexts, "items": items}


def _tileset_exports(state):
    native, directory = state["native_directory"], PurePosixPath(state["directory"])
    result = []
    for a in [*state["registrations"].values(), *state["terrains"].values(), *state["parts"].values()]:
        key = PurePosixPath(a["tsx"]).relative_to(directory).as_posix().replace("/", "--")
        result.append({"path": a["tsx"], "capacity": a["capacity"], "export": f"{native}/exports/tilesets/{key[:-4]}.tsj"})
    return result


def _render_plan(manifest, state, declared):
    return {"schema_version": 1, "consumer": manifest["id"], "cell_size": manifest["cell_size"],
            "expected_inventory_sha256": sha256(json_bytes(declared)), "output": state["native_directory"],
            "stages": [{"id": i["id"], "field_sha256": i["field_sha256"], "mode": i["mode"],
                        **{k: i[k] for k in ("tmx", "png", "overlay", "ground")}}
                       for i in declared["items"] if i["kind"] == "draw-stage"],
            "contexts": declared["contexts"], "tilesets": _tileset_exports(state)}


def _write_image(root, path, image):
    root.write(path, png_bytes(image))


def _schematic(field, size):
    image = Image.new("RGBA", (12*size, 12*size), (31, 38, 47, 255))
    draw = ImageDraw.Draw(image)
    for k in range(13):
        draw.line((k*size, 0, k*size, 12*size), fill=(78, 88, 99, 255))
        draw.line((0, k*size, 12*size, k*size), fill=(78, 88, 99, 255))
    for y, row in enumerate(field):
        for x, value in enumerate(row):
            r = max(2, size//8)
            draw.ellipse((x*size-r, y*size-r, x*size+r, y*size+r), fill=(231, 177, 62, 255) if value else (97, 129, 172, 255))
    return image


def _crop(image, rect):
    x, y, w, h = rect
    require(w > 0 and h > 0 and 0 <= x and 0 <= y and x+w <= image.width and y+h <= image.height, "Prescribed review crop is incomplete/out of bounds")
    return image.crop((x, y, x+w, y+h))


def prepare_render(inputs, manifest, manifest_path, candidate, *, allow_test_trust=False):
    root = inputs.root
    require(not root.exists(f"{manifest['output_root']}/proofs/{candidate}-seal.json"), "Frozen candidate cannot be rendered/rebuilt again")
    state = _candidate(inputs, manifest, manifest_path, candidate, allow_test_trust=allow_test_trust)
    native = state["native_directory"]
    root.mkdir(native)
    root.write(f"{native}/owner.json", json_bytes({"schema_version": 1, "consumer": manifest["id"], "candidate": candidate,
               "operation": "render", "producer": PRODUCER, "source_approval": state["approval"], "test_only": state["approval"]["test_only"]}))
    declared = _declaration(manifest, state)
    expected_path = f"{native}/expected-inventory.json"
    root.write(expected_path, json_bytes(declared))
    state.update({"declared": declared, "contexts": declared["contexts"], "expected_inventory_path": expected_path,
                  "expected_inventory_sha256": sha256(json_bytes(declared))})
    families = []
    for (pack, family), a in state["terrains"].items():
        ground = next((g for (p, _), g in state["terrains"].items() if p == pack and g["family"]["mode"] == "opaque"), None)
        require(a["family"]["mode"] == "opaque" or ground is not None, "Alpha native cases need reviewed opaque ground")
        bootstrap = f"{native}/bootstrap/{pack}-{family}.tmx"
        refs = [a] if a["family"]["mode"] == "opaque" else [ground, a]
        node, first = map_root(12, 12, manifest["cell_size"], refs, bootstrap)
        if a["family"]["mode"] == "alpha":
            add_layer(node, "ground-context", [first[ground["tsx"]]+ground["mask_ids"][0]]*144, 12, 12, {"entity": "ground-context"})
        add_layer(node, "persistent-terrain", [first[a["tsx"]]+a["mask_ids"][0]]*144 if a["family"]["mode"] == "opaque" else [0]*144, 12, 12, {"entity": "persistent-terrain"})
        finalize_map(root, bootstrap, node)
        control = ground or a
        control_node = read_tileset(root, control["tsx"])["xml"]
        atlas = resolve_reference(root, control["tsx"], control_node.find("image").get("source"))
        families.append({"pack": pack, "family": family, "mode": a["family"]["mode"], "tsx": a["tsx"], "mask_ids": {str(m): i for m, i in a["mask_ids"].items()},
                         "bootstrap": bootstrap, "terrain_tileset_index": len(refs)-1, "terrain_layer_index": len(refs)-1,
                         "ground_tsx": ground["tsx"] if ground else None, "control_atlas": atlas})
    cases = [{**case, "recipe_sha256": sha256(json_bytes(case))} for case in declared["draw"]["cases"]]
    draw_plan = {"schema_version": 1, "consumer": manifest["id"], "cells": 12, "cell_size": manifest["cell_size"],
                 "expected_inventory_sha256": state["expected_inventory_sha256"], "output": f"{native}/stages", "families": families,
                 "cases": cases, "expected_stages": len(declared["draw"]["items"])}
    render_plan = _render_plan(manifest, state, declared)
    # All expected pixels, schematics and crop declarations predate native work.
    stages = {(case["id"], stage["id"]): stage for case in declared["draw"]["cases"] for stage in case["stages"]}
    descriptions = {d["path"]: d for d in state["descriptions"]}
    for item in declared["items"]:
        if item["kind"] == "draw-stage":
            a = state["terrains"][(item["pack"], item["family"])]
            field = stages[(item["case"], item["stage"])]["expected_field"]
            ground = next((g["patterns"][0] for (p, _), g in state["terrains"].items() if p == item["pack"] and g["family"]["mode"] == "opaque"), None) if item["mode"] == "alpha" else None
            pixels = expectation.draw_pixels(field, a["patterns"], manifest["cell_size"], ground)
            _write_image(root, item["intent_png"], _schematic(field, manifest["cell_size"]))
            if item["expected_overlay"]:
                _write_image(root, item["expected_overlay"], unpremultiply(expectation.draw_pixels(field, a["patterns"], manifest["cell_size"])))
        else:
            pixels, _ = expectation.reconstruct(descriptions[item["map"]], manifest["cell_size"], item["elapsed_ms"])
        expected = unpremultiply(pixels)
        _write_image(root, item["expected"], expected)
        for crop in item["crops"]:
            _write_image(root, crop["expected"], _crop(expected, crop["pixel_rect"]))
        for key in ("tmx", "record", "png", "overlay", "ground"):
            if item.get(key):
                require(not root.exists(item[key]), "Foreign preexisting native artifact")
                with root.parent(item[key], create=True):
                    pass
    for entry in render_plan["tilesets"]+declared["contexts"]:
        for key in ("export", "png"):
            if entry.get(key):
                with root.parent(entry[key], create=True):
                    pass
    with root.parent(f"{native}/animation/placeholder.png", create=True):
        pass
    state["draw_plan_path"], state["render_plan_path"] = f"{native}/draw-plan.json", f"{native}/render-plan.json"
    root.write(state["draw_plan_path"], json_bytes(draw_plan))
    root.write(state["render_plan_path"], json_bytes(render_plan))
    inputs.recheck()
    return state


def _wang(mask, mode):
    b = 2 if mode == "opaque" else 0
    return [0, 1 if mask&2 else b, 0, 1 if mask&4 else b, 0, 1 if mask&8 else b, 0, 1 if mask&1 else b]


def _cells(layer):
    require(layer.tag == "layer" and xml_integer(layer, "width") == xml_integer(layer, "height") == 12
            and layer.get("visible", "1") == "1" and layer.get("opacity", "1") == "1"
            and all(xml_integer(layer, k, "0") == 0 for k in ("x", "y", "offsetx", "offsety")), "Native finite/effective layer geometry changed")
    data = layer.find("data")
    require(data is not None and data.get("encoding") == "csv" and data.get("compression") is None and not list(data), "Native complete finite CSV required")
    values = [int(v) for v in (data.text or "").split(",")]
    require(len(values) == 144 and all(0 <= v < 0x10000000 for v in values), "Truncated/extra/flagged native cells")
    return values


def _draw_readback(root, manifest, state, item, stage, record):
    closed(record, ("schema_version", "id", "case", "stage", "pack", "family", "mode", "field_sha256", "recipe_sha256", "raw_requests", "accepted_requests",
                    "captured_prior", "pruned_outside", "in_bounds_unchanged_by_clip", "corrections_enabled", "erasing_enabled", "cells", "ground_ids", "readback_equal", "width", "height", "tmx"), "complete native stage record")
    integer(record["width"], "native record width", 1)
    integer(record["height"], "native record height", 1)
    require(type(record["schema_version"]) is int and record["schema_version"] == 1 and record["width"] == record["height"] == 12, "Native record dimensions/version")
    for key in ("id", "case", "stage", "pack", "family", "mode", "field_sha256", "recipe_sha256", "tmx"):
        require(record[key] == item[key], f"Wrong/frozen native {key}")
    require(all(record[k] is True for k in ("in_bounds_unchanged_by_clip", "corrections_enabled", "erasing_enabled", "readback_equal")), "Native clipping/stock-default/readback proof missing")
    for key in ("raw_requests", "accepted_requests", "captured_prior"):
        for request in array(record[key], "native " + key):
            require(type(request) is list and len(request) == 3, "Native vertex record must be [x,y,value]")
            x, y, value = request
            require(type(x) is type(y) is int and
                    (type(value) is int and value in (0, 1) or key == "captured_prior" and value is None),
                    "Native vertex record requires strict integer coordinates/materials")
    require(all(record[k] == stage[k] for k in ("raw_requests", "accepted_requests", "captured_prior")), "Native recipe/request/clipping/prior mismatch")
    for outside in array(record["pruned_outside"], "pruned actual outside cells"):
        closed(outside, ("x", "y", "id", "flags", "tileset"), "native outside cell")
        integer(outside["id"], "pruned actual local ID")
        integer(outside["flags"], "pruned actual flags")
        require(type(outside["tileset"]) is str, "Pruned outside tileset identity must be text")
        require(type(outside["x"]) is type(outside["y"]) is int and not (0 <= outside["x"] < 12 and 0 <= outside["y"] < 12)
                and outside["flags"] == 0, "Native clip changed/pruned an inside cell")
    a = state["terrains"][(item["pack"], item["family"])]
    masks = [m for row in expectation.intent_masks(stage["expected_field"]) for m in row]
    expected_ids = [a["mask_ids"][m] for m in masks]
    cell = closed(record["cells"], ("ids", "flags", "wang_ids", "tilesets"), "actual native cell readback")
    for key in cell:
        require(len(array(cell[key], key)) == 144, "Native cell readback must contain every finite cell")
    for local, flags, vector in zip(cell["ids"], cell["flags"], cell["wang_ids"]):
        if local is not None:
            integer(local, "actual native local ID")
        integer(flags, "actual native flags")
        require(len(array(vector, "actual native Wang vector")) == 8, "Native Wang vector requires all eight values")
        for color in vector:
            integer(color, "actual native Wang color")
    if record["ground_ids"] is not None:
        require(len(array(record["ground_ids"], "actual ground IDs")) == 144, "Incomplete native ground readback")
        for local in record["ground_ids"]:
            integer(local, "actual ground ID")
    require(cell["ids"] == expected_ids and cell["flags"] == [0]*144
            and cell["wang_ids"] == [[0]*8 if local is None else _wang(m, item["mode"]) for local, m in zip(expected_ids, masks)]
            and cell["tilesets"] == [None if local is None else str(root.path/a["tsx"]) for local in expected_ids],
            "Actual native IDs/flags/tilesets/Wang masks do NOT satisfy independent intent")
    node = ET.fromstring(root.read(item["tmx"])[0])
    require(node.tag == "map" and node.get("infinite") == "0" and node.get("orientation") == "orthogonal"
            and node.get("renderorder") == "right-down" and node.get("tiledversion") == "1.12.2"
            and xml_integer(node, "width") == xml_integer(node, "height") == 12
            and xml_integer(node, "tilewidth") == xml_integer(node, "tileheight") == manifest["cell_size"], "Native saved dimensions changed")
    props = property_values(node)
    require(props.get("draw_identity") == item["id"] and props.get("expected_field_sha256") == item["field_sha256"], "Previous native stage/field copied into current stage")
    refs = node.findall("tileset")
    layers = node.findall("layer")
    require(len(layers) == len(refs) == (2 if item["mode"] == "alpha" else 1)
            and not node.findall("objectgroup") and not node.findall("group"), "Wrong native stage layer/reference inventory")
    if item["mode"] == "alpha":
        ground = next(g for (p, _), g in state["terrains"].items() if p == item["pack"] and g["family"]["mode"] == "opaque")
        require(xml_integer(refs[0], "firstgid") == 1 and resolve_reference(root, item["tmx"], refs[0].get("source")) == ground["tsx"], "Native ground TSX identity")
        require(_cells(layers[0]) == [ground["mask_ids"][0]+1]*144 and record["ground_ids"] == [ground["mask_ids"][0]]*144, "Alpha erase changed ground IDs/GIDs")
        first = ground["capacity"]+1
    else:
        first = 1
        require(record["ground_ids"] is None, "Unexpected opaque ground layer")
    require(xml_integer(refs[-1], "firstgid") == first and resolve_reference(root, item["tmx"], refs[-1].get("source")) == a["tsx"], "Native external terrain TSX identity/GID")
    require(_cells(layers[-1]) == [0 if local is None else first+local for local in expected_ids], "Native serialized old-tile/null/flags mismatch")
    return a, masks


def _command(root, result, resource=None, *, argv=None):
    closed(result, ("argv", "returncode", "logs", "sentinel", "overflow", "complete"), "complete native invocation")
    arguments = array(result["argv"], "actual native argv", True)
    require(all(type(v) is str and 0 < len(v) <= 4096 and "\0" not in v for v in arguments)
            and (argv is None or arguments == [str(v) for v in argv]), "Wrong actual runtime/resource/plan/timing arguments")
