def _native_vertex_field(record):
    """Recover shared vertices from ACTUAL native Wang readback, not intent."""
    field = [[None]*13 for _ in range(13)]
    for index, vector in enumerate(record["cells"]["wang_ids"]):
        x, y = index%12, index//12
        for dx, dy, corner in ((0, 0, 7), (1, 0, 1), (1, 1, 3), (0, 1, 5)):
            value = int(vector[corner] == 1)
            previous = field[y+dy][x+dx]
            require(previous is None or previous == value, "Native adjacent cells disagree at shared topology vertex")
            field[y+dy][x+dx] = value
    return field


